#!/usr/bin/env bash
# Regenerates Sources/SigstoreTUF/EmbeddedRoots.swift from the TUF root.json
# files in Sources/SigstoreTUF/Resources (sigstore-go v1.4.1
# pkg/tuf/repository/{root,staging_root}.json).
#
# sigstore-go embeds these with go:embed; we compile them into the binary as
# base64 literals instead of a SwiftPM resource bundle (resource bundles
# make swift-build on Windows flaky, see PROGRESS.md).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/Sources/SigstoreTUF/Resources"
OUT="$ROOT/Sources/SigstoreTUF/EmbeddedRoots.swift"

emit() {
  local name="$1" file="$2"
  echo "    /// \`$(basename "$file")\`, sha256 $(shasum -a 256 "$file" | cut -d' ' -f1)."
  echo "    static let $name: [String] = ["
  base64 < "$file" | tr -d '\n' | fold -w 76 | sed 's/.*/        "&",/'
  echo "    ]"
}

{
  echo "// GENERATED by scripts/embed-tuf-roots.sh. Do not edit."
  echo ""
  echo "enum EmbeddedRoots {"
  emit root "$SRC/root.json"
  echo ""
  emit stagingRoot "$SRC/staging_root.json"
  echo "}"
} > "$OUT"
echo "Generated $OUT"
