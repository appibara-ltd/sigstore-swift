#!/usr/bin/env bash
# Regenerates Tests/<target>/EmbeddedTestData.swift from each test target's
# data directory (Tests/SigstoreTests/Fixtures, Tests/SigstoreMLDSATests/Vectors,
# Tests/SigstoreCryptoExtrasTests/Vectors).
#
# Test data is compiled in as base64 string literals instead of a SwiftPM
# resource bundle: swift-build on Windows intermittently fails its "Touch"
# step on resource bundle directories (see PROGRESS.md). The data
# directories stay in the repository as the source of truth and are
# excluded from the targets in Package.swift.
#
# Run after adding or changing any file in those directories; CI fails when
# the generated files are out of date.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"

generate() {
  local target="$1" dir="$2"
  local base="$ROOT/Tests/$target"
  local out="$base/EmbeddedTestData.swift"
  {
    echo "// GENERATED by scripts/embed-test-data.sh from Tests/$target/$dir. Do not edit."
    echo ""
    echo "import Foundation"
    echo ""
    echo "/// The files under \`$dir/\`, compiled in (no resource bundle)."
    echo "enum EmbeddedTestData {"
    echo "    /// Path relative to the target directory (\`$dir/...\`) → base64 contents."
    echo "    static let base64: [String: String] = ["
    (cd "$base" && find "$dir" -type f ! -name '.gitkeep' ! -name '.DS_Store' | LC_ALL=C sort) | while IFS= read -r rel; do
      echo "        // sha256 $(shasum -a 256 "$base/$rel" | cut -d' ' -f1)"
      echo "        \"$rel\": \"\"\""
      base64 < "$base/$rel" | tr -d '\n' | fold -w 76 | sed 's/^/        /'
      echo ""
      echo "        \"\"\","
    done
    echo "    ]"
    echo ""
    echo "    /// The contents of \`path\` (\`$dir/...\`)."
    echo "    static func data(_ path: String) throws -> Data {"
    echo "        guard let encoded = base64[path] else { throw CocoaError(.fileNoSuchFile, userInfo: [NSFilePathErrorKey: path]) }"
    echo "        guard let data = Data(base64Encoded: encoded, options: .ignoreUnknownCharacters) else {"
    echo "            throw CocoaError(.fileReadCorruptFile, userInfo: [NSFilePathErrorKey: path])"
    echo "        }"
    echo "        return data"
    echo "    }"
    echo ""
    echo "    /// Paths of the files under \`directory\`, relative to it (\`/\` separators)."
    echo "    static func files(under directory: String) -> [String] {"
    echo "        let prefix = directory.hasSuffix(\"/\") ? directory : directory + \"/\""
    echo "        return base64.keys.filter { \$0.hasPrefix(prefix) }.map { String(\$0.dropFirst(prefix.count)) }.sorted()"
    echo "    }"
    echo "}"
  } > "$out"
  echo "Generated $out"
}

generate SigstoreTests Fixtures
generate SigstoreMLDSATests Vectors
generate SigstoreCryptoExtrasTests Vectors
